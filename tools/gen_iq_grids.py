#!/usr/bin/env python3
"""Generate src/iq_grids.h: the codebooks of ggml's i-quants (IQ1_S / IQ1_M, IQ2_XXS / IQ2_XS / IQ2_S, IQ3_XXS /
IQ3_S, IQ4_XS), for src/iquants.h and the numpy reference (tests/ggufmini.py reads the header back).

Usage: python3 tools/gen_iq_grids.py path/to/ggml-common.h > src/iq_grids.h          (any Python 3; stdlib only)

ggml-common.h is llama.cpp's ggml/src/ggml-common.h (MIT, THIRD_PARTY_NOTICES.md); the tables are data of the
formats (the decoders index them with the bits stored in the files), copied value for value:
  iq2xxs_grid[256], iq2xs_grid[512], iq2s_grid[1024]  uint64: 8 magnitudes (bytes 8, 25 or 43) per entry
  iq3xxs_grid[256], iq3s_grid[512]                    uint32: 4 magnitudes per entry (IQ3_XXS 4..62, IQ3_S 1..15)
  iq1s_grid[2048]                                     uint64: 8 int8 values -1, 0, 1 per entry (IQ1_S and IQ1_M)
  kvalues_iq4nl[16]                                   int8: IQ4_XS's (and IQ4_NL's) non-linear values
Derived (not in ggml), for the AVX-512 kernels (src/iquants.h):
  iq1s_code          every entry of a grid as small codes, value j at bits B j .. B j + B - 1: its position in the
                     grid's alphabet (B = 2: IQ2 {8, 25, 43}, IQ1 {-1, 0, 1}; B = 3: IQ3_XXS {4, 12, .., 52, 62},
                     IQ3_S {1, 3, .., 15}), uint16 (the repacked IQ1 layouts store these instead of indices); the IQ2 / IQ3 codes
                     only as the byte tables below
  iq2*_clo, iq2*_chi the IQ2 codes' low and high bytes (values 0..3, 4..7), uint8: vpermi2b tables
  iq3*_ca, iq3*_cb   the IQ3 codes of values 0, 1 and of 2, 3 (code | code << 3), uint8: vpermi2b tables
ksigns_iq2xs (the 7 stored sign bits of 8 values, completed with even parity) is not copied: it is the
expression s | (popcount(s) & 1) << 7 (src/iquants.h), checked here against ggml's table.
"""
import re
import sys

TABLES = [  # (name, C type, entries, hex digits per entry or 0 for decimal)
    ("iq2xxs_grid", "uint64_t", 256, 16),
    ("iq2xs_grid", "uint64_t", 512, 16),
    ("iq2s_grid", "uint64_t", 1024, 16),
    ("iq3xxs_grid", "uint32_t", 256, 8),
    ("iq3s_grid", "uint32_t", 512, 8),
    ("iq1s_grid", "uint64_t", 2048, 16),
    ("kvalues_iq4nl", "int8_t", 16, 0),
]


def table(src, name):
    m = re.search(r"GGML_TABLE_BEGIN\(\s*\w+\s*,\s*%s\s*,[^)]*\)(.*?)GGML_TABLE_END\(\)" % name, src, re.S)
    if not m:
        sys.exit(f"gen_iq_grids: table {name} not found")
    return [int(v, 0) for v in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", m.group(1))]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = open(sys.argv[1], encoding="utf-8").read()
    ks = table(src, "ksigns_iq2xs")
    want = [s | (bin(s).count("1") & 1) << 7 for s in range(128)]
    if ks != want:
        sys.exit("gen_iq_grids: ksigns_iq2xs is not the parity completion of its index")
    out = ["// Generated by tools/gen_iq_grids.py from ggml's ggml-common.h (llama.cpp, MIT: THIRD_PARTY_NOTICES.md).",
           "// Do not edit. The codebooks of the i-quant formats (src/iquants.h); tests/ggufmini.py parses this file.",
           "#ifndef RUNQ_IQ_GRIDS_H", "#define RUNQ_IQ_GRIDS_H", "", "#include <stdint.h>", ""]
    for name, ctype, n, hexd in TABLES:
        vals = table(src, name)
        if len(vals) != n:
            sys.exit(f"gen_iq_grids: {name} has {len(vals)} entries, expected {n}")
        per = 4 if hexd == 16 else 8 if hexd == 8 else 16
        out.append(f"static const {ctype} {name}[{n}] = {{")
        for i in range(0, n, per):
            row = vals[i:i + per]
            if hexd:
                out.append("    " + ", ".join(f"0x{v:0{hexd}x}" for v in row) + ",")
            else:
                out.append("    " + ", ".join(str(v) for v in row) + ",")
        out.append("};")
        out.append("")
    codes = [  # (name, grid, bytes per entry, bits per value, alphabet, extra zero entries)
        ("iq2xxs_code", "iq2xxs_grid", 8, 2, [8, 25, 43], 0), ("iq2xs_code", "iq2xs_grid", 8, 2, [8, 25, 43], 0),
        ("iq2s_code", "iq2s_grid", 8, 2, [8, 25, 43], 0), ("iq3xxs_code", "iq3xxs_grid", 4, 3, [4, 12, 20, 28, 36, 44, 52, 62], 0),
        ("iq3s_code", "iq3s_grid", 4, 3, [1, 3, 5, 7, 9, 11, 13, 15], 0), ("iq1s_code", "iq1s_grid", 8, 2, [255, 0, 1], 0)]
    for cname, gname, nb, bits, alpha, extra in codes:
        vals = []
        for e in table(src, gname):
            c = 0
            for j in range(nb):
                byte = (e >> 8 * j) & 255
                if byte not in alpha:
                    sys.exit(f"gen_iq_grids: {gname} has a value {byte} outside its alphabet")
                c |= alpha.index(byte) << bits * j
            vals.append(c)
        vals += [0] * extra
        if cname.startswith("iq3"):
            for half, nm in ((0, "ca"), (1, "cb")):
                bv = [(v >> 6 * half) & 63 for v in vals]
                out.append(f"// derived: the codes of values {2 * half}, {2 * half + 1} of {cname}")
                out.append(f"static const uint8_t {cname[:-5]}_{nm}[{len(bv)}] __attribute__((aligned(64))) = {{")
                for i in range(0, len(bv), 16):
                    out.append("    " + ", ".join(f"0x{v:02x}" for v in bv[i:i + 16]) + ",")
                out.append("};")
                out.append("")
        if cname.startswith("iq2"):
            for half, nm in ((0, "clo"), (1, "chi")):
                bv = [(v >> 8 * half) & 255 for v in vals]
                out.append(f"// derived: byte {half} of {cname}")
                out.append(f"static const uint8_t {cname[:-5]}_{nm}[{len(bv)}] __attribute__((aligned(64))) = {{")
                for i in range(0, len(bv), 16):
                    out.append("    " + ", ".join(f"0x{v:02x}" for v in bv[i:i + 16]) + ",")
                out.append("};")
                out.append("")
        if cname == "iq1s_code":
            out.append(f"// derived: {gname} as {bits}-bit codes per value (alphabet {alpha})")
            out.append(f"static const uint16_t {cname}[{len(vals)}] = {{")
            for i in range(0, len(vals), 12):
                out.append("    " + ", ".join(f"0x{v:04x}" for v in vals[i:i + 12]) + ",")
            out.append("};")
            out.append("")
    out.append("#endif // RUNQ_IQ_GRIDS_H")
    print("\n".join(out))


if __name__ == "__main__":
    main()
